begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select plan(1);
insert into auth.users(id) values('00000000-0000-0000-0000-00000000a101'),('00000000-0000-0000-0000-00000000b202'),('00000000-0000-0000-0000-00000000c303');
insert into public.profiles(user_id,display_name) values('00000000-0000-0000-0000-00000000a101','Owner'),('00000000-0000-0000-0000-00000000b202','Member'),('00000000-0000-0000-0000-00000000c303','Outsider');
set local role authenticated;
do $$
declare owner_id uuid:='00000000-0000-0000-0000-00000000a101'; member_id uuid:='00000000-0000-0000-0000-00000000b202'; outsider_id uuid:='00000000-0000-0000-0000-00000000c303';
  room uuid; first_place uuid; second_place uuid; invite text; statuses jsonb; caught boolean;
begin
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  room:=(public.room_command('create',jsonb_build_object('title','Policy test','start',current_date+1,'end',current_date+10,'deadline',now()+interval '1 day'))->>'id')::uuid;
  invite:=public.room_command('invite',jsonb_build_object('room',room))->>'token';
  first_place:=(public.room_command('propose',jsonb_build_object('room',room,'name','First'))->>'id')::uuid;
  second_place:=(public.room_command('propose',jsonb_build_object('room',room,'name','Second'))->>'id')::uuid;
  perform public.room_command('availability',jsonb_build_object('day',current_date+2,'answer','free'));
  perform public.room_command('vote',jsonb_build_object('room',room,'place',first_place,'selected',true));
  perform set_config('request.jwt.claim.sub',outsider_id::text,true);
  if exists(select 1 from public.trip_rooms where id=room) then raise exception 'Outsider read room'; end if;
  if exists(select 1 from public.profile_availability where user_id=owner_id) then raise exception 'Outsider read private availability'; end if;
  caught:=false; begin perform public.room_availability(room,current_date,current_date+5); exception when insufficient_privilege then caught:=true; end;
  if not caught then raise exception 'Outsider read group availability'; end if;
  caught:=false; begin perform public.room_command('message',jsonb_build_object('room',room,'body','not allowed')); exception when insufficient_privilege then caught:=true; end;
  if not caught then raise exception 'Outsider sent chat'; end if;
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  perform public.room_command('join',jsonb_build_object('room',room,'token',invite));
  if not exists(select 1 from public.trip_rooms where id=room) then raise exception 'Member cannot read room'; end if;
  caught:=false; begin perform public.room_command('close',jsonb_build_object('room',room)); exception when insufficient_privilege then caught:=true; end;
  if not caught then raise exception 'Member closed voting'; end if;
  caught:=false; begin perform public.room_command('delete',jsonb_build_object('room',room)); exception when insufficient_privilege then caught:=true; end;
  if not caught then raise exception 'Member deleted room'; end if;
  perform public.room_command('vote',jsonb_build_object('room',room,'place',second_place,'selected',true));
  perform public.room_command('vote',jsonb_build_object('room',room,'place',first_place,'selected',true));
  perform public.room_command('vote',jsonb_build_object('room',room,'place',first_place,'selected',true));
  if (select count(*) from public.room_votes where room_id=room and user_id=member_id)<>2 then raise exception 'Multiple approvals or idempotent vote failed'; end if;
  perform public.room_command('vote',jsonb_build_object('room',room,'place',first_place,'selected',false));
  if (select count(*) from public.room_votes where room_id=room and user_id=member_id)<>1 then raise exception 'Vote change failed'; end if;
  perform public.room_command('message',jsonb_build_object('room',room,'body','Hello'));
  statuses:=public.room_availability(room,current_date+2,current_date+2);
  if not statuses @> jsonb_build_array(jsonb_build_object('user_id',owner_id,'answer','free')) then raise exception 'Shared availability missing'; end if;
  if not statuses @> jsonb_build_array(jsonb_build_object('user_id',member_id,'answer',null)) then raise exception 'Missing answer was not unknown'; end if;
  perform public.room_command('availability',jsonb_build_object('room',room,'day',current_date+2,'answer','busy'));
  if not exists(select 1 from public.profile_availability where user_id=member_id and day=current_date+2 and answer='busy') then raise exception 'Room edit did not update global availability'; end if;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform public.room_command('close',jsonb_build_object('room',room));
  caught:=false; begin perform public.room_command('vote',jsonb_build_object('room',room,'place',second_place,'selected',true)); exception when invalid_parameter_value then caught:=true; end;
  if not caught then raise exception 'Late vote allowed'; end if;
  perform public.room_command('confirm',jsonb_build_object('room',room,'date',current_date+2,'place',second_place));
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  caught:=false; begin perform public.room_command('rsvp',jsonb_build_object('room',room,'version',0,'response','going')); exception when invalid_parameter_value then caught:=true; end;
  if not caught then raise exception 'Stale RSVP accepted'; end if;
  perform public.room_command('rsvp',jsonb_build_object('room',room,'version',1,'response','going'));
  if not exists(select 1 from public.calendar_event_jobs where user_id=member_id and room_id=room and payload->>'version'='1') then raise exception 'Calendar not queued'; end if;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform public.room_command('confirm',jsonb_build_object('room',room,'date',current_date+3,'place',first_place));
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  if exists(select 1 from public.calendar_event_jobs where user_id=member_id and room_id=room and payload is not null) then raise exception 'Old calendar plan retained'; end if;
  perform public.room_command('rsvp',jsonb_build_object('room',room,'version',2,'response','going'));
  if (select count(*) from public.calendar_event_jobs where user_id=member_id and room_id=room)<>1 then raise exception 'Duplicate event link'; end if;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform public.room_command('kick',jsonb_build_object('room',room,'user',member_id));
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  if exists(select 1 from public.trip_rooms where id=room) then raise exception 'Kicked member still reads room'; end if;
  if exists(select 1 from public.calendar_event_jobs where room_id=room and payload is not null) then raise exception 'Kick retained appointment'; end if;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  invite:=public.room_command('invite',jsonb_build_object('room',room))->>'token';
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  perform public.room_command('join',jsonb_build_object('room',room,'token',invite));
  if not exists(select 1 from public.trip_rooms where id=room) then raise exception 'Kicked member cannot rejoin with new invite'; end if;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform public.room_command('ban',jsonb_build_object('room',room,'user',member_id));
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  caught:=false; begin perform public.room_command('join',jsonb_build_object('room',room,'token',invite)); exception when insufficient_privilege then caught:=true; end;
  if not caught then raise exception 'Banned member joined'; end if;
  if exists(select 1 from public.room_messages where room_id=room) then raise exception 'Banned member read chat'; end if;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform public.room_command('unban',jsonb_build_object('room',room,'user',member_id));
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  perform public.room_command('join',jsonb_build_object('room',room,'token',invite));
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform public.room_command('revoke_invites',jsonb_build_object('room',room));
  perform set_config('request.jwt.claim.sub',outsider_id::text,true);
  caught:=false; begin perform public.room_command('join',jsonb_build_object('room',room,'token',invite)); exception when invalid_parameter_value then caught:=true; end;
  if not caught then raise exception 'Revoked invite accepted'; end if;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform public.room_command('delete',jsonb_build_object('room',room));
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  if exists(select 1 from public.calendar_event_jobs where room_id=room and payload is not null) then raise exception 'Deleted room kept an appointment'; end if;
end $$;
reset role;
select pass('room roles, availability privacy, tied votes, deadlines, versioned RSVP, event outbox, ban, revoke, delete');
select * from finish();
rollback;
